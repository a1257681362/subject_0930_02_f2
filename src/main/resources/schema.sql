-- ============================================================
-- aqua-2 水质采样计划与缺测补录
-- 规则版本化：任务生成时固化规则版本快照，新版本只重指"未开始(PENDING)"任务；
-- 原值不可改：补录仅以 SUPPLEMENT 行追加，审核后才进入池塘健康曲线；
-- 所有关键动作落 t_wq_change_evidence 证据链。
-- ============================================================

-- 指标规则版本（DRAFT/PUBLISHED）。任务绑定具体版本，天然隔离后续版本。
CREATE TABLE IF NOT EXISTS t_wq_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    remark VARCHAR(255),
    published_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_rule_version_no UNIQUE (version_no)
);

-- 阶段规则：不同养殖阶段配置采样频率（相对投苗日的天区间 + 间隔天数）
CREATE TABLE IF NOT EXISTS t_wq_stage_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    stage_code VARCHAR(24) NOT NULL,
    stage_name VARCHAR(64) NOT NULL,
    start_day INT NOT NULL,
    end_day INT NOT NULL,
    interval_days INT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_stage_rule UNIQUE (version_id, stage_code)
);

-- 指标规则：各阶段下指标的正常范围与是否必测
CREATE TABLE IF NOT EXISTS t_wq_metric_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    stage_code VARCHAR(24) NOT NULL,
    metric_code VARCHAR(32) NOT NULL,
    metric_name VARCHAR(64) NOT NULL,
    unit VARCHAR(16),
    min_value DECIMAL(10,3),
    max_value DECIMAL(10,3),
    required INT NOT NULL DEFAULT 1,
    sort_no INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_metric_rule UNIQUE (version_id, stage_code, metric_code)
);
CREATE INDEX IF NOT EXISTS idx_wq_metric_version_stage ON t_wq_metric_rule (version_id, stage_code);

-- 水质采样计划：一个计划覆盖多个池塘
CREATE TABLE IF NOT EXISTS t_wq_sampling_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_no VARCHAR(32) NOT NULL,
    plan_name VARCHAR(64) NOT NULL,
    rule_version_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_plan_no UNIQUE (plan_no)
);

-- 计划-池塘明细（记录生成任务时该池对应的在养批次）
CREATE TABLE IF NOT EXISTS t_wq_plan_pond (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_plan_pond UNIQUE (plan_id, pond_id)
);

-- 采样任务：按池按阶段频率排期生成；rule_version_id/stage 为生成时快照
-- 状态：PENDING 未开始 / DRAFT 草稿暂存 / SUBMITTED 已提交 / APPROVED 审核通过 / REJECTED 驳回
CREATE TABLE IF NOT EXISTS t_wq_sampling_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(64) NOT NULL,
    plan_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT,
    stage_code VARCHAR(24) NOT NULL,
    stage_name VARCHAR(64) NOT NULL,
    rule_version_id BIGINT NOT NULL,
    planned_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    sampled_at TIMESTAMP,
    submitted_at TIMESTAMP,
    reviewed_at TIMESTAMP,
    review_comment VARCHAR(255),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_task_no UNIQUE (task_no),
    CONSTRAINT uk_wq_task_slot UNIQUE (plan_id, pond_id, planned_date)
);
CREATE INDEX IF NOT EXISTS idx_wq_task_pond_date ON t_wq_sampling_task (pond_id, planned_date);
CREATE INDEX IF NOT EXISTS idx_wq_task_status ON t_wq_sampling_task (status);

-- 测量值：ORIGINAL 原测（每任务每指标一条，提交后冻结）；SUPPLEMENT 补录（只追加，永不覆盖原值）
-- 缺测：value 为空且 missing_reason 必填（提交时强校验）
-- review_status：DRAFT / SUBMITTED / APPROVED / REJECTED / PENDING（补录待审核）
CREATE TABLE IF NOT EXISTS t_wq_measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    metric_code VARCHAR(32) NOT NULL,
    metric_name VARCHAR(64) NOT NULL,
    unit VARCHAR(16),
    metric_value DECIMAL(10,3),
    missing_reason VARCHAR(255),
    record_type VARCHAR(16) NOT NULL,
    supersedes_id BIGINT,
    review_status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    supplement_reason VARCHAR(255),
    review_comment VARCHAR(255),
    measured_at TIMESTAMP,
    reviewed_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wq_measurement_task ON t_wq_measurement (task_id, metric_code);

-- 池塘健康曲线：任务（含补录）经主管审核后才写入；每任务每指标一个点，补录审核通过更新该点（测量原值不动）
CREATE TABLE IF NOT EXISTS t_wq_health_curve_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT,
    task_id BIGINT NOT NULL,
    metric_code VARCHAR(32) NOT NULL,
    metric_name VARCHAR(64) NOT NULL,
    unit VARCHAR(16),
    curve_date DATE NOT NULL,
    metric_value DECIMAL(10,3) NOT NULL,
    source VARCHAR(24) NOT NULL,
    measurement_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_curve_point UNIQUE (task_id, metric_code)
);
CREATE INDEX IF NOT EXISTS idx_wq_curve_pond_date ON t_wq_health_curve_point (pond_id, curve_date);

-- 证据链：规则发布/任务生成与重指/草稿修改/提交/审核/补录/曲线写入全程留痕
CREATE TABLE IF NOT EXISTS t_wq_change_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_type VARCHAR(32) NOT NULL,
    biz_id BIGINT,
    action VARCHAR(48) NOT NULL,
    detail VARCHAR(1000),
    before_json CLOB,
    after_json CLOB,
    operator VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wq_evidence_biz ON t_wq_change_evidence (biz_type, biz_id);

-- 幂等请求记录：同一 Idempotency-Key 的重复 POST 直接回放首次响应，不产生第二条业务结果
CREATE TABLE IF NOT EXISTS t_wq_idempotent_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key VARCHAR(64) NOT NULL,
    method VARCHAR(8) NOT NULL,
    path VARCHAR(255) NOT NULL,
    status_code INT NOT NULL,
    response_body CLOB,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_wq_idempotent_key UNIQUE (request_key)
);

